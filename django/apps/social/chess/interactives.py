def attach(lesson: dict | None) -> dict | None:
    if not lesson:
        return None
    extra = INTERACTIVES.get(lesson["slug"]) or {}
    if not extra:
        return lesson
    return {**lesson, **extra}


def interactive_slugs() -> list[str]:
    return list(INTERACTIVES.keys())
