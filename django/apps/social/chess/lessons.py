class LessonCatalog:
    """Small helper with Django-friendly cached access patterns."""

    def __init__(self, lessons=None, chapters=None):
        self._lessons = list(lessons or LESSONS)
        self._chapters = list(chapters or CHAPTERS)

    @cached_property
    def by_slug(self) -> dict:
        return {les["slug"]: les for les in self._lessons}

    @cached_property
    def ordered_slugs(self) -> list[str]:
        chapter_order = {c["slug"]: i for i, c in enumerate(self._chapters)}
        return [
            les["slug"]
            for les in sorted(
                self._lessons,
                key=lambda x: (chapter_order.get(x["chapter"], 99), self._lessons.index(x)),
            )
        ]

    def get(self, slug: str):
        from .interactives import attach
        return attach(self.by_slug.get((slug or "").strip()))

    def chapter_lessons(self, chapter_slug: str) -> list[dict]:
        from .interactives import attach
        return [attach(les) for les in self._lessons if les["chapter"] == chapter_slug]

    def next_incomplete(self, done_slugs: set[str]):
        for slug in self.ordered_slugs:
            if slug not in done_slugs:
                return self.get(slug)
        return None

    def chapter_progress(self, done_slugs: set[str]) -> list[dict]:
        out = []
        for ch in self.chapters_with_lessons():
            slugs = [les["slug"] for les in ch["lessons"]]
            done = sum(1 for s in slugs if s in done_slugs)
            total = len(slugs) or 1
            out.append({
                **ch,
                "done": done,
                "pct": int(round(100 * done / total)),
            })
        return out

    def neighbors(self, slug: str) -> tuple[dict | None, dict | None]:
        order = self.ordered_slugs
        if slug not in order:
            return None, None
        i = order.index(slug)
        prev_slug = order[i - 1] if i > 0 else None
        next_slug = order[i + 1] if i + 1 < len(order) else None
        return self.get(prev_slug) if prev_slug else None, self.get(next_slug) if next_slug else None

    def chapters_with_lessons(self) -> list[dict]:
        out = []
        for ch in self._chapters:
            items = self.chapter_lessons(ch["slug"])
            out.append({**ch, "lessons": items, "count": len(items)})
        return out


CATALOG = LessonCatalog()


def lesson_by_slug(slug: str):
    return CATALOG.get(slug)
