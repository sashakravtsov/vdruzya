def tip_by_slug(slug: str) -> dict | None:
    for t in TIPS:
        if t["slug"] == slug:
            return t
    return None


def tips_by_chapter() -> list[dict]:
    out = []
    for ch in CHAPTERS:
        items = [t for t in TIPS if t["chapter"] == ch["slug"]]
        out.append({**ch, "tips": items, "n": len(items)})
    return out
