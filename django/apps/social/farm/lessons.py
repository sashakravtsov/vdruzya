def lesson_by_slug(slug: str) -> dict | None:
    for les in LESSONS:
        if les["slug"] == slug:
            return les
    return None


def lessons_by_chapter() -> list[dict]:
    out = []
    for ch in CHAPTERS:
        items = [l for l in LESSONS if l["chapter"] == ch["slug"]]
        out.append({**ch, "lessons": items, "n": len(items)})
    return out
